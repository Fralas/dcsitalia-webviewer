export const BIOS_SPLASH_DURATION_MS = 5000;
export const BIOS_PROGRESS_BAR_WIDTH = 42;

export function buildBiosProgressBar(percent) {
  const clamped = Math.max(0, Math.min(100, Math.round(percent)));
  const filled = Math.round((clamped / 100) * BIOS_PROGRESS_BAR_WIDTH);
  const bar = '#'.repeat(filled).padEnd(BIOS_PROGRESS_BAR_WIDTH, '-');
  return `[${bar}] ${String(clamped).padStart(3, ' ')}%`;
}
